def build_menu() -> list[dict[str, object]]:
    rng = random.Random(SEED)
    menu = list(MENU)
    for index, spec in enumerate(EXTRA_SPECS, start=1):
        (
            item_id,
            name,
            description,
            category,
            price,
            diet_tags,
            allergens,
            ingredients,
            spice_level,
            prep_minutes,
            calories,
            protein_g,
        ) = spec
        menu.append(
            {
                "id": item_id,
                "name": name,
                "description": description,
                "category": category,
                "price": price,
                "diet_tags": diet_tags,
                "allergens": allergens,
                "ingredients": ingredients,
                "spice_level": spice_level,
                "available": rng.random() > 0.08,
                "prep_minutes": prep_minutes,
                "calories": calories,
                "protein_g": protein_g,
                "popularity": round(0.24 + rng.random() * 0.58, 2),
            }
        )
    return menu


